#!/bin/bash
# start.sh
# Starts backend (FastAPI/uvicorn) and frontend (static server) as
# detached background processes, so the terminal can be closed
# afterwards. Automatically picks free ports to avoid conflicts with
# other projects. Opens the homepage in the default browser.

set -e

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PID_DIR="${PROJECT_ROOT}/.run"
LOG_DIR="${PROJECT_ROOT}/.run/logs"

mkdir -p "${PID_DIR}" "${LOG_DIR}"

BACKEND_PID_FILE="${PID_DIR}/backend.pid"
FRONTEND_PID_FILE="${PID_DIR}/frontend.pid"
PORT_INFO_FILE="${PID_DIR}/ports.env"

# ---------- Guard: refuse to start if already running ----------
if [ -f "${BACKEND_PID_FILE}" ] && kill -0 "$(cat "${BACKEND_PID_FILE}")" 2>/dev/null; then
  echo "Backend already running (PID $(cat "${BACKEND_PID_FILE}"))."
  echo "Run ./stop.sh first if you want to restart."
  exit 1
fi

# ---------- Helper: find a free TCP port starting from a base ----------
find_free_port() {
  local port=$1
  while lsof -i TCP:"${port}" -sTCP:LISTEN >/dev/null 2>&1; do
    port=$((port + 1))
  done
  echo "${port}"
}

BACKEND_PORT=$(find_free_port 8000)
FRONTEND_PORT=$(find_free_port 5500)

# Save chosen ports so stop.sh / re-runs can reference them if needed
cat > "${PORT_INFO_FILE}" <<EOF
BACKEND_PORT=${BACKEND_PORT}
FRONTEND_PORT=${FRONTEND_PORT}
EOF

# ---------- Sync frontend config.js with the actual backend port ----------
CONFIG_FILE="${PROJECT_ROOT}/frontend/js/config.js"
cat > "${CONFIG_FILE}" <<EOF
// Auto-generated by start.sh - do not edit manually.
const BACKEND_PORT = ${BACKEND_PORT};
const API_BASE_URL = \`http://localhost:\${BACKEND_PORT}\`;
EOF

# ---------- Start backend ----------
cd "${PROJECT_ROOT}/backend"
nohup python3 -m uvicorn app.main:app --port "${BACKEND_PORT}" \
  > "${LOG_DIR}/backend.log" 2>&1 &
echo $! > "${BACKEND_PID_FILE}"
disown

# ---------- Start frontend ----------
cd "${PROJECT_ROOT}/frontend"
nohup python3 -m http.server "${FRONTEND_PORT}" \
  > "${LOG_DIR}/frontend.log" 2>&1 &
echo $! > "${FRONTEND_PID_FILE}"
disown

# ---------- Wait briefly for servers to come up ----------
sleep 1

HOME_URL="http://localhost:${FRONTEND_PORT}/index.html"

echo "Backend running at  http://localhost:${BACKEND_PORT}  (PID $(cat "${BACKEND_PID_FILE}"))"
echo "Frontend running at http://localhost:${FRONTEND_PORT} (PID $(cat "${FRONTEND_PID_FILE}"))"
echo "Homepage: ${HOME_URL}"
echo "Logs: ${LOG_DIR}/backend.log, ${LOG_DIR}/frontend.log"
echo "Run ./stop.sh to stop both servers."

# ---------- Open browser (cross-platform best effort) ----------
if command -v xdg-open >/dev/null 2>&1; then
  xdg-open "${HOME_URL}" >/dev/null 2>&1 &
elif command -v open >/dev/null 2>&1; then
  open "${HOME_URL}" >/dev/null 2>&1 &
elif command -v start >/dev/null 2>&1; then
  start "${HOME_URL}" >/dev/null 2>&1 &
else
  echo "Could not detect a command to open the browser automatically."
  echo "Please open ${HOME_URL} manually."
fi